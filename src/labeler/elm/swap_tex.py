"""LaTeX tables of the ELM reference swap, in the layout of the AE benchmark tables.

`write` turns the record of `scripts/labeler/elm_reference_swap.py` into
`table_elm_benchmark.tex` (AUROC and F1 of each method against the review and against
the legacy table, as `table_ae_benchmark.tex`), `table_elm_swap_full.tex` (precision,
recall and F1 against both, with the legacy table and the expert labels as rows, as
`table_reference_swap_full.tex`), and one benchmark table per extra set. Every cell is
read from the record; none is typed.
"""

from __future__ import annotations

import math
from pathlib import Path

from . import compare

DOMAIN_NOTE = (
    "The DSM and legacy onset table were built on WPQH phases with "
    "breakthrough-ELM targets; comparisons with reviewed occupancy involve "
    "definition and domain shift."
)

NAME = compare.NAME
ROWS = (
    (NAME["ours"], "elm-ours"),
    (NAME["elmo"], "elm-elmo"),
    (NAME["detect"], compare.DISPLAY_NAME[NAME["detect"]]),
    (NAME["clock"], "elm-clock"),
    (NAME["dsm"], compare.DISPLAY_NAME[NAME["dsm"]]),
    (NAME["exposed"], compare.DISPLAY_NAME[NAME["exposed"]]),
    (NAME["init"], compare.DISPLAY_NAME[NAME["init"]]),
)
ALWAYS = "always present"
EXPOSED = {NAME["dsm"], NAME["init"], "elm-dsm-detect-exposed"}


def method_label(key: str, *, multiline: bool = False) -> str:
    """Keep upstream reuse visible and wrap table labels at readable font sizes."""
    label = {ALWAYS: "always-present", "elm-feature-only": "elm-feature"}.get(
        key, dict(ROWS).get(key, key)
    )
    label = label.replace("1×128", r"$1\times128$")
    if multiline:
        label = {
            NAME["exposed"]: ("elm-dsm-detect (source stats)"),
            NAME["init"]: ("elm-dsm-detect (source weights/stats)"),
        }.get(key, label)
    if key in EXPOSED:
        label += r"$^{\ddagger}$"
    return label


def exposure_heading(columns: int) -> str:
    return (
        r"\midrule\multicolumn{"
        + str(columns)
        + r"}{l}{\emph{Supplemental: upstream data reused$^{\ddagger}$}} \\"
    )


def cell(point: float | None, ci, digits=3, ci_digits=3) -> str:
    if point is None or math.isnan(point):
        return "--"
    out = f"{point:.{digits}f}"
    if ci is not None and not math.isnan(ci[0]):
        out += f" {{\\scriptsize[{ci[0]:.{ci_digits}f}, {ci[1]:.{ci_digits}f}]}}"
    return out


def metric_cell(res: dict, metric: str) -> str:
    if res["point"].get(metric) is None:
        return "--"
    out = cell(res["point"][metric], res.get("ci95", {}).get(metric))
    if metric == "f1" and res["point"].get("recall", 0) >= 0.99:
        out += r"$^{\dagger}$"
    return out


def delta_cell(change: dict | None) -> str:
    """A paired change `value` with its shot-bootstrap interval, signed."""
    if not change or change.get("value") is None or math.isnan(change["value"]):
        return "--"
    out = f"{change['value']:+.3f}"
    ci = change.get("ci95")
    if ci is not None and not math.isnan(ci[0]):
        out += f" {{\\scriptsize[{ci[0]:+.3f}, {ci[1]:+.3f}]}}"
    return out


def f1_with_pr(res: dict) -> str:
    """Numerical F1 and interval, with precision/recall beneath when available."""
    out = metric_cell(res, "f1")
    p = res["point"]
    if "precision" in p and "recall" in p:
        out = (
            r"\shortstack{"
            + out
            + r"\\{\scriptsize "
            + f"P={p['precision']:.3f}, R={p['recall']:.3f}"
            + "}}"
        )
    return out


def header(record: dict, source: str) -> str:
    return (
        f"% generated by labeler.elm.swap_tex from {source}"
        f" (git {record['git']}); do not edit\n"
    )


def benchmark_table(res: dict, ref_a: str, ref_b: str, labels, record, source) -> str:
    """`res[ref_a]` and `res[ref_b]` are `score_reference` outputs."""
    a, b = res[ref_a], res[ref_b]
    change = res.get("comparison", {}).get("auroc_change_paired", {})
    lines = [
        header(record, source)
        + "\\footnotesize\\setlength{\\tabcolsep}{0.75pt}\n"
        + "\\begin{tabular}{@{}lccccc@{}}",
        "\\toprule",
        (
            f"& \\multicolumn{{2}}{{c}}{{{labels[0]} "
            f"({100 * a['prevalence']:.0f}\\% present)}} "
            f"& \\multicolumn{{2}}{{c}}{{{labels[1]} "
            f"({100 * b['prevalence']:.0f}\\% present)}} & Paired change \\\\"
        ),
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-6}",
        "Method & AUROC & F1 & AUROC & F1 & $\\Delta$AUROC \\\\",
        "\\midrule",
    ]
    exposed = False
    for key, _ in ROWS:
        if key not in a["methods"]:
            continue
        ra, rb = a["methods"][key], b["methods"][key]
        if key in EXPOSED and not exposed:
            lines.append(exposure_heading(6))
            exposed = True
        label = method_label(key, multiline=True)
        lines.append(
            f"{label} & {metric_cell(ra, 'auroc')} & {metric_cell(ra, 'f1')} & "
            f"{metric_cell(rb, 'auroc')} & {metric_cell(rb, 'f1')} & "
            f"{delta_cell(change.get(key))} \\\\"
        )
    lines.append("\\midrule")
    ra, rb = a["methods"][ALWAYS], b["methods"][ALWAYS]
    lines.append(
        f"{method_label(ALWAYS)} & {ra['point']['auroc']:.3f} & {metric_cell(ra, 'f1')} & "
        f"{rb['point']['auroc']:.3f} & {metric_cell(rb, 'f1')} & -- \\\\"
    )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


def prf(res: dict) -> str:
    p = res["point"]
    return f"{p['precision']:.3f} & {p['recall']:.3f} & {metric_cell(res, 'f1')}"


def main_table(res: dict, record: dict, source: str) -> str:
    """Reviewed/onset AUROC and numerical F1; companions retain P/R and gaps."""
    return benchmark_table(
        res,
        "reviewed",
        "legacy",
        ("Reviewed occupancy", "Legacy onset bins"),
        record,
        source,
    )


def finding_one(record: dict) -> dict:
    """Finding 1 on the AE-style known-majority cells (primary) and the strict bins.

    The known-majority cells (`interval_audit.known_review_majority`) have at least
    25 ms of legacy coverage and a reviewed present or absent state with at least
    25 ms of occupancy; the strict bins are the interior bins the method rows use.
    """
    audit = record["interval_audit"]["known_review_majority"]
    strict = record["swap"]["overlap"]["finding_1"]
    strict_point = strict["as_methods"]["legacy_table_vs_reviewed"]["point"]
    return {
        "cells": audit["bins"],
        "M": audit["M"],
        "P": audit["P"],
        "recall": audit["point"]["recall"],
        "precision": audit["point"]["precision"],
        "strict_bins": strict["bins"],
        "strict_M": strict["M"],
        "strict_P": strict["P"],
        "strict_recall": strict_point["recall"],
        "strict_precision": strict_point["precision"],
    }


def paired_intervals(record: dict) -> tuple[int, list[tuple[str, str, dict]]]:
    """Eligible paired legacy-minus-review AUROC intervals and those excluding zero.

    Counts every finite interval in the all-overlap and BES panels; the intervals
    are unadjusted for multiplicity and the BES panel has seven shots.
    """
    total, hits = 0, []
    for scope, tag in (("all", "overlap"), ("BES", "overlap_bes")):
        panel = record["swap"][tag]
        for key, row in panel["comparison"]["auroc_change_paired"].items():
            lo, hi = row["ci95"] or (math.nan, math.nan)
            if math.isnan(lo):
                continue
            total += 1
            if lo > 0 or hi < 0:
                hits.append((scope, key, row))
    return total, hits


def full_table(res: dict, record: dict, source: str, legacy_label=None) -> str:
    a, b = res["reviewed"], res["legacy"]
    one = finding_one(record)
    leg_vs_rev = res["finding_1"]["as_methods"]["legacy_table_vs_reviewed"]
    legacy_label = legacy_label or "legacy onset table"
    lines = [
        header(record, source) + "\\begin{tabular}{lcccccc}",
        "\\toprule",
        (
            "& \\multicolumn{3}{c}{Reference: Reviewed occupancy} & "
            f"\\multicolumn{{3}}{{c}}{{Reference: {legacy_label}}} \\\\"
        ),
        "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
        "Method & P & R & F1 & P & R & F1 \\\\",
        "\\midrule",
    ]
    exposed = False
    for key, _ in ROWS:
        if key in a["methods"]:
            if key in EXPOSED and not exposed:
                lines.append(exposure_heading(7))
                exposed = True
            label = method_label(key, multiline=True)
            lines.append(
                f"{label} & {prf(a['methods'][key])} & {prf(b['methods'][key])} \\\\"
            )
    lines.append("\\midrule")
    lp = leg_vs_rev["point"]
    identity = r"1.000 {\scriptsize[1.000, 1.000]}$^{\dagger}$"
    lines.append(
        f"{legacy_label} & {prf(leg_vs_rev)} & 1.000 & 1.000 & {identity} \\\\"
    )
    lines.append(
        f"{method_label(ALWAYS)} & {prf(a['methods'][ALWAYS])} & "
        f"{prf(b['methods'][ALWAYS])} \\\\"
    )
    # the expert labels read as a detector of the legacy marks: the legacy table's
    # precision against the review is the expert's recall against the legacy table
    oracle_f1 = cell(_f1(lp["recall"], lp["precision"]), leg_vs_rev["ci95"]["f1"], 3, 3)
    lines.append(
        f"Reviewed occupancy (oracle) & 1.000 & 1.000 & {identity} & {lp['recall']:.3f} & "
        f"{lp['precision']:.3f} & {oracle_f1} \\\\"
    )
    lines += [
        "\\midrule",
        (
            f"Prevalence of present bins & \\multicolumn{{3}}{{c}}"
            f"{{{a['prevalence']:.3f}}} & \\multicolumn{{3}}{{c}}"
            f"{{{b['prevalence']:.3f}}} \\\\"
        ),
        (
            f"Finding 1, {one['cells']} known-majority cells (primary) & "
            f"\\multicolumn{{6}}{{c}}{{$|M|={one['M']}$, $|P|={one['P']}$; legacy "
            f"recall {one['recall']:.3f}, precision {one['precision']:.3f}}} \\\\"
        ),
        (
            f"Strict interior bins ({one['strict_bins']}, rows above) & "
            f"\\multicolumn{{6}}{{c}}{{$|M|={one['strict_M']}$, "
            f"$|P|={one['strict_P']}$; legacy recall {one['strict_recall']:.3f}, "
            f"precision {one['strict_precision']:.3f}}} \\\\"
        ),
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ]
    return "\n".join(lines)


def _f1(p: float, r: float) -> float:
    return 2 * p * r / (p + r) if p + r else float("nan")


def signed(value: float, ci=None) -> str:
    """`+0.031` or `+0.031 [-0.019, +0.081]`."""
    out = f"{value:+.3f}"
    if ci is not None:
        out += f" [{ci[0]:+.3f}, {ci[1]:+.3f}]"
    return out


NUMBER_WORDS = (
    "zero",
    "one",
    "two",
    "three",
    "four",
    "five",
    "six",
    "seven",
    "eight",
    "nine",
    "ten",
    "eleven",
    "twelve",
)


def count_word(n: int) -> str:
    return NUMBER_WORDS[n] if 0 <= n < len(NUMBER_WORDS) else str(n)


def ranking_sentence(*panels: dict) -> str:
    """What the reference change does to each panel's method orders, from the record."""
    auroc_moved = any(p["comparison"]["order_changes"]["auroc"] for p in panels)
    pairs = max(len(p["comparison"]["order_flips"]["f1"]) for p in panels)
    text = (
        "The AUROC order changes. "
        if auroc_moved
        else "No ranking change: the AUROC order is unchanged. "
    )
    if pairs:
        text += (
            f"The F1 order of {count_word(pairs)} method pairs differs "
            "(review-tuned thresholds; descriptive). "
        )
    return text


def excluding_zero(record: dict) -> str:
    """The unadjusted paired intervals that exclude zero, as a count of the total."""
    total, hits = paired_intervals(record)
    if not hits:
        return f"All {count_word(total)} unadjusted paired intervals include zero. "
    shots = count_word(record["swap"]["overlap_bes"]["n_shots"])
    named = "; ".join(
        f"{method_label(key)} on the {scope} shots ({signed(row['value'], row['ci95'])}"
        f"; {shots} shots)"
        if scope == "BES"
        else f"{method_label(key)} on the {scope} shots "
        f"({signed(row['value'], row['ci95'])})"
        for scope, key, row in hits
    )
    verb = "excludes" if len(hits) == 1 else "exclude"
    return (
        f"{count_word(len(hits)).capitalize()} of {total} unadjusted paired "
        f"intervals {verb} zero: {named}. "
    )


def main_caption(
    record: dict, ours: dict | None = None, photodiode: dict | None = None
) -> str:
    """The main swap caption; every number is read from the swap record.

    `ours` is the elm-ours evaluation record; with it the caption compares elm-elmo's
    AUROC on the BES overlap shots, with its interval, with its AUROC on the whole
    BES subset. `photodiode` is the upstream-versus-fresh PCPHD02/03 comparison.
    """
    overlap, bes = record["swap"]["overlap"], record["swap"]["overlap_bes"]
    one = finding_one(record)
    change = overlap["comparison"]["auroc_change_paired"][NAME["dsm"]]
    interval = change["ci95"]
    inside = interval[0] <= 0 <= interval[1]
    in_sample = len(overlap["dsm_refit_training_shots"])
    text = (
        f"ELM reference swap on {count_word(overlap['n_shots'])} overlap shots "
        f"({count_word(bes['n_shots'])} with BES); inconclusive. On {one['cells']} "
        "known-majority cells the legacy onset table has recall "
        f"{one['recall']:.3f} and precision {one['precision']:.3f} against the "
        f"review ($|M|={one['M']}$ present cells missed, $|P|={one['P']}$ absent "
        f"cells marked present). Method rows use {one['strict_bins']} strict "
        "interior bins. AUROC compares references; F1 uses review-tuned thresholds; "
        "$\\Delta$ is the paired legacy-minus-review AUROC change with its "
        "shot-bootstrap interval; $^{\\dagger}$ marks recall $\\geq0.99$. "
        + ranking_sentence(overlap, bes)
        + f"The {method_label(NAME['dsm'])} change {signed(change['value'])} is "
        f"in-sample on {in_sample}/{overlap['n_shots']} shots and "
        + ("within its interval" if inside else "outside its interval")
        + "; no AE Finding-2 analogue is established. "
        + excluding_zero(record)
    )
    if ours is not None:
        elmo = NAME["elmo"]
        res = bes["reviewed"]["methods"][elmo]
        whole = ours["sets"]["bes73"]["methods"][elmo]["point"]["auroc"]
        lo, hi = res["ci95"]["auroc"]
        contains = lo <= whole <= hi
        text += (
            f"{elmo} scores {cell(res['point']['auroc'], res['ci95']['auroc'])} on "
            f"the {count_word(bes['n_shots'])} BES shots against {whole:.3f} on "
            f"bes73; the interval {'contains' if contains else 'excludes'} that "
            "value, so no shift is established. "
        )
    if photodiode:
        text += (
            "The upstream PCPHD02/03 export the detection adaptation reads on "
            f"these shots equals a fresh fetch in {photodiode['identical']} of "
            f"{photodiode['records']} records, sample for sample."
        )
    else:
        text += (
            "All overlap shots use the upstream WPQH PCPHD02/03 export in the "
            "detection adaptation."
        )
    return text.rstrip()


def write(
    record: dict,
    out_dir: Path,
    source="outputs/labeler/elm/swap/evaluation.json",
    ours: dict | None = None,
    photodiode: dict | None = None,
):
    """Four consolidated appendix tables; complete diagnostics remain in JSON."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    panels = []
    for tag in ("overlap", "overlap_bes"):
        res = record["swap"][tag]
        panels.append(panel_heading(res) + main_table(res, record, source))
    caption = main_caption(record, ours, photodiode)
    held, held_bes = (
        record["swap"]["overlap_dsm_heldout"],
        record["swap"]["overlap_bes_dsm_heldout"],
    )
    tables = {
        "table_elm_swap.tex": wrap_table(
            "\n\\medskip\n".join(panels), caption, "tab:elm-swap", domain_note=False
        ),
        "table_elm_swap_full.tex": wrap_table(
            full_table(record["swap"]["overlap"], record, source),
            "Fixed-prediction precision, recall and F1 against both references on "
            "the strict interior bins; Finding 1 on the known-majority cells "
            "(primary) is in the last rows. Eight overlap shots; identity oracle "
            "results hold by definition. Brackets show eligible shot-bootstrap "
            "intervals; F1 is review-tuned. "
            f"The {count_word(held['n_shots'])} shots ({held_bes['n_shots']} with "
            "BES) outside original DSM fitting are too few for intervals.",
            "tab:elm-swap-full",
        ),
        "table_elm_swap_sensitivity.tex": wrap_table(
            sensitivity_table(record, source),
            "Legacy onset bins and covered-gap occupancy sensitivities. "
            "Known-majority cells have at least 25 ms of legacy coverage and are "
            "labelled present or absent by at least 25 ms of that reviewed state. "
            "Missing coverage is never bridged. Tiny positive-shot subsets are "
            "descriptive only; eligible intervals use 1000 shot draws.",
            "tab:elm-swap-sensitivity",
        ),
        "table_elm_swap_rankings.tex": wrap_table(
            ranking_table(record, source, "auroc"),
            "AUROC point orders with fixed predictions on strict interior bins "
            "and known majority bins within every method's coverage. "
            "Eight-shot evidence is inconclusive; "
            "point crossings cannot establish population ranking reversal. "
            "Methods reusing upstream weights or statistics are supplemental.",
            "tab:elm-swap-rankings",
        ),
    }
    for name, content in tables.items():
        (out_dir / name).write_text(content)


def panel_heading(res: dict) -> str:
    if res.get("has_elmo"):
        text = f"{res['n_shots']} BES shots, elm-elmo chunks"
    else:
        text = f"All {res['n_shots']} overlap shots"
    if not res.get("dsm_refit_training_shots"):
        text += "; outside original DSM fitting and selection"
    return f"\\textbf{{{text}: {res['reviewed']['bins']} bins}}\\par\\smallskip\n"


def bes_point_order_crosses(record: dict) -> bool:
    """Whether clean DSM and ELM-O exchange point-AUROC order in the BES swap."""
    res = record["swap"]["overlap_bes"]
    clean, elmo = NAME["detect"], NAME["elmo"]

    def delta(reference):
        methods = reference["methods"]
        return methods[clean]["point"]["auroc"] - methods[elmo]["point"]["auroc"]

    baseline = delta(res["reviewed"])
    return any(
        baseline * delta(reference) < 0
        for reference in (
            res["legacy"],
            *(r["legacy"] for r in res["occupancy"].values()),
        )
    )


def sensitivity_table(record: dict, source: str) -> str:
    lines = [
        header(record, source) + r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r"Legacy reference & Bins & $|M|$ & $|P|$ & P & R & F1 \\",
        r"\midrule",
    ]
    audits = [("all-covered", record["interval_audit"]["known_review_majority"])]
    for key, audit in record["interval_audit_occupancy"].items():
        audits.append((key, audit["known_review_majority"]))
    groups = [("Known-majority cells (8 shots)", audits)]
    for tag, res in record["swap"].items():
        refs = [("onset", res["finding_1"])] + [
            (key, value["finding_1"]) for key, value in res["occupancy"].items()
        ]
        scope = (
            f"{res['n_shots']} BES shots, elm-elmo chunks"
            if res["has_elmo"]
            else f"All {res['n_shots']} overlap shots"
        )
        if "heldout" in tag:
            scope += ", outside original DSM fitting and selection"
        groups.append((scope, refs))
    for scope, refs in groups:
        lines.append(r"\multicolumn{7}{l}{\textbf{" + scope + r"}} \\")
        for key, result in refs:
            label = (
                "onset bins"
                if key in ("onset", "all-covered")
                else ("$\\tau=" + key.removeprefix("gap_").removesuffix("ms") + "$ ms")
            )
            p = result["point"]
            lines.append(
                f"{label} & {result['bins']} & {result['M']} & "
                f"{result['P']} & {p['precision']:.3f} & "
                f"{metric_cell(result, 'recall')} & {metric_cell(result, 'f1')} \\\\"
            )
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines += [r"\end{tabular}", ""]
    return "\n".join(lines)


def ranking_table(record: dict, source: str, metric: str) -> str:
    lines = [
        header(record, source) + r"\begin{tabular}{lp{0.73\textwidth}}",
        r"\toprule",
        f"Reference & {metric.upper()}: methods, best first " + r"\\",
        r"\midrule",
    ]
    scopes = [
        (tag, res)
        for tag, res in record["swap"].items()
        if tag in ("overlap", "overlap_bes")
    ]
    scopes += [
        ("all-covered " + tag, res)
        for tag, res in record.get("all_covered_swap", {}).items()
    ]
    for tag, res in scopes:
        refs = [("reviewed", res["reviewed"]), ("onset bins", res["legacy"])] + [
            (f"$\\tau={r['gap_ms']}$ ms", r["legacy"])
            for r in res.get("occupancy", {}).values()
        ]
        scope = (
            f"{res['n_shots']} BES shots, elm-elmo chunks"
            if res["has_elmo"]
            else f"All {res['n_shots']} overlap shots"
        )
        scope += f"; {res['reviewed']['bins']} bins"
        if tag.startswith("all-covered"):
            label = (
                "Known majority, detection coverage"
                if "detection_common" in tag
                else "Known majority, complete scores"
            )
            scope = label + ": " + scope
        lines.append(r"\multicolumn{2}{l}{\textbf{" + scope + r"}} \\")
        for name, reference in refs:
            # Historical initialization variants have their own numerical appendix.
            order = " $>$ ".join(
                method_label(n)
                for n in reference["ranking"][metric]
                if n not in (NAME["init"], "elm-dsm-detect-exposed")
            )
            lines.append(f"{name} & {order} " + r"\\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines += [r"\end{tabular}", ""]
    return "\n".join(lines)


def swap_caption(res: dict, gap: int | None = None, full: bool = False) -> str:
    reference = (
        "legacy onset-bin presence"
        if gap is None
        else f"legacy occupancy with $\\tau={gap}$ ms covered gaps"
    )
    return (
        f"Reviewed occupancy versus {reference}: {res['n_shots']} shots/"
        f"{res['reviewed']['bins']} identical 50 ms interior bins. "
        + (
            "Precision, recall and numerical F1 include the reference and oracle "
            "rows; identity agreement is by definition. "
            if full
            else "AUROC and numerical F1 use identical predictions. "
        )
        + (
            "F1 retains review-tuned thresholds and is descriptive. "
            if full
            else "F1 retains review-tuned thresholds; only AUROC compares references. "
        )
        + "Brackets show shot-bootstrap intervals; $^{\\ddagger}$ marks methods "
        "reusing upstream weights or statistics and $^{\\dagger}$ marks recall "
        "$\\geq0.99$."
    )


def wrap_table(
    body: str, caption: str, label: str, domain_note: bool | None = None
) -> str:
    """A `table*` float; `domain_note` forces or suppresses the WPQH-domain sentence."""
    wanted = label.startswith("tab:elm-swap") or label in (
        "tab:elm-dsm-native",
        "tab:elm-dsm-own-target",
    )
